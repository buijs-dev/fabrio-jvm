    private fun rejected(items: List<DeleteBatchItem<ShipmentId>>): List<Throwable?> =
        rejectedInputs(
            "SHIPMENT",
            items.map { it.id.value },
            items.map { it.expectedVersion },
            VERSION,
        )

    private suspend fun delete(
        sql: QueryExecutor,
        items: List<DeleteBatchItem<ShipmentId>>,
    ): List<Result<Unit>> {
        val rejected = rejected(items)
        val candidates = items.indices.filter { rejected[it] == null }
        val matched =
            sql.batch(
                ShipmentSql.LOCK_FOR_DELETE,
                candidates.map { index ->
                    val item = items[index]
                    listOf(item.id.value, VERSION.valueOf(item.expectedVersion), currentTenant.require())
                },
            )
        val lockedRows = matched.mapNotNull { it.singleOrNull() }
        // P4.4: a restricting child that exists keeps its owner.
        val restricted =
            lockedRows
                .filter { it.uuidOrNull("customs_declaration_id") != null }
                .map { it.uuid("public_id") }
                .toSet()
