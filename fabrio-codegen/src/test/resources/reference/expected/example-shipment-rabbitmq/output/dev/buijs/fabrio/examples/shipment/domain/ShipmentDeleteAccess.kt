@Singleton
internal class ShipmentDeleteAccess(
    private val transactionalExecutor: TransactionalExecutor,
    private val currentTenant: CurrentTenant,
) : DeleteAccess<ShipmentId> {

    override suspend fun delete(
        id: ShipmentId,
        expectedVersion: Any?,
