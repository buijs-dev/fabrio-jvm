        val storageIds = locked.map { it.long("storage_id") }
        val publicIds = locked.map { it.uuid("public_id") }
        sql.execute(ShipmentSql.DELETE_TAGS_OF, listOf(storageIds.toTypedArray()))
        removeLinesOf(sql, storageIds)
        removePackagesOf(sql, storageIds)
        sql.execute(ShipmentSql.DELETE, listOf(publicIds.toTypedArray(), currentTenant.require()))
        val customsDeclarationKeys = locked.mapNotNull { it.uuidOrNull("customs_declaration_id") }
        if (customsDeclarationKeys.isNotEmpty()) {
            sql.execute(ShipmentSql.DELETE_CUSTOMS_DECLARATION, listOf(customsDeclarationKeys.toTypedArray()))
        }
        val removed =
            candidates.filterIndexed { position, _ -> matched[position].isNotEmpty() }.toSet()
        return items.indices.map { index ->
            val item = items[index]
            rejected[index]?.let { Result.failure(it) }
                ?: if (item.id.value in restricted) {
                    Result.failure(
                        dev.buijs.fabrio.persistence.core.api.ConstraintViolationException(
                            dev.buijs.fabrio.persistence.core.api.ConstraintKind.FOREIGN_KEY,
                            "SHIPMENT",
                            "customs_declaration_id",
                            null,
                            "SHIPMENT is still referenced by its customsDeclaration (onDelete: restrict)",
                            null,
                            null,
                        ),
                    )
