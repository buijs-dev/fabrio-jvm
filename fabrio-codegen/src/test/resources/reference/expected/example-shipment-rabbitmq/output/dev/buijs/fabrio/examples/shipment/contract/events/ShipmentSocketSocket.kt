/**
 * The stream `shipmentSocket` over a WebSocket (subprotocol `cloudevents.json`): one text message per CloudEvent, resumed from the `lastEventId` query parameter (A5).
 *
 * Auto-generated by fabrio:codegen. Do not edit manually.
 */
@WebSocket(path = "/streams/shipments/socket")
@RolesAllowed("shipments:read")
internal class ShipmentSocketSocket(
    private val hub: StreamHub,
    private val access: ShipmentSocketAccess,
    private val identity: SecurityIdentity,
) {
    @OnOpen
    fun open(connection: WebSocketConnection): Multi<String> {
        val principal = identity.principal
        val subscriberTenant = identity.getAttribute<Any?>(TENANT_ATTRIBUTE)?.toString()
        val lastEventId =
            connection.handshakeRequest().query()
                ?.split('&')
                ?.map { it.split('=', limit = 2) }
                ?.firstOrNull { it[0] == "lastEventId" }
                ?.getOrNull(1)
                ?.let { URLDecoder.decode(it, Charsets.UTF_8) }
        return hub
            .open(SPEC, lastEventId, subscriberTenant) { access.canRead(principal, it) }
            .map(CloudEventJson::encode)
    }

    private companion object {
        val SPEC =
            StreamSpec(
                name = "shipmentSocket",
                types = setOf("com.example.shipment.approved.v1", "com.example.shipment.cancelled.v1"),
                replay = Duration.parse("PT1H"),
            )
    }
}
