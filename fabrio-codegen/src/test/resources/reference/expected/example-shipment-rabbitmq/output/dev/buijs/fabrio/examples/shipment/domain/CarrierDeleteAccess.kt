/**
 * Generated delete-side data access for `Carrier`: one statement of [CarrierSql] per
 * step, for every item at once, in one transaction.
 *
 * Auto-generated by fabrio:codegen. Do not edit manually.
 */
@Singleton
internal class CarrierDeleteAccess(
    private val transactionalExecutor: TransactionalExecutor,
    private val standardActorGenerator: StandardActorGenerator,
) : DeleteAccess<UUID> {

    override suspend fun delete(
        id: UUID,
        expectedVersion: Any?,
    ) {
        transactionalExecutor.withTransaction { sql ->
            delete(sql, listOf(DeleteBatchItem(id, expectedVersion))).single().getOrThrow()
        }
    }

    /**
     * Deletes [items] at once; an item that matched nothing, or is rejected up front, gets its own
     * failure. When the batch fails as a whole, every item is deleted on its own instead.
     */
    override suspend fun deleteAll(items: List<DeleteBatchItem<UUID>>): BatchResult<Unit> =
        batchOrEach(
            items,
            all = { all -> transactionalExecutor.withTransaction { sql -> delete(sql, all) } },
            each = { delete(it.id, it.expectedVersion) },
            rejected = rejected(items),
        )

    private fun rejected(items: List<DeleteBatchItem<UUID>>): List<Throwable?> =
        rejectedInputs(
            "CARRIER",
            items.map { it.id },
            items.map { it.expectedVersion },
            null,
        )

    private suspend fun delete(
        sql: QueryExecutor,
        items: List<DeleteBatchItem<UUID>>,
    ): List<Result<Unit>> {
        val rejected = rejected(items)
        val candidates = items.indices.filter { rejected[it] == null }
        val actor = standardActorGenerator.generate()
        val matched =
            sql.batch(
                CarrierSql.SOFT_DELETE,
                candidates.map { index ->
                    val item = items[index]
                    listOf(item.id, actor)
                },
            )
        val removed =
            candidates.filterIndexed { position, _ -> matched[position].isNotEmpty() }.toSet()
        return items.indices.map { index ->
            val item = items[index]
            rejected[index]?.let { Result.failure(it) }
                ?: if (index in removed) {
                    Result.success(Unit)
                } else {
                    Result.failure(
                        sql.diagnoseMiss(
                            "CARRIER",
                            CarrierSql.ACTIVE_ROW,
                            item.id,
                            item.expectedVersion,
                            versioned = false,
                        ),
                    )
                }
        }
    }

    /**
     * Restores the soft-deleted row [id] (lifecycle L3.7): clears its marker, and who deleted
     * it (P6.10). A live row succeeds unchanged; a missing one fails with
     * [EntityNotFoundException]. A restore that breaks a unique key fails like any write
     * that does (`unique`, L3.8), and the row stays deleted.
     */
    suspend fun restore(id: UUID) {
        transactionalExecutor.withTransaction { sql ->
            val restored = sql.query(CarrierSql.RESTORE, listOf(id))
            val stored = restored.isNotEmpty() ||
                sql.queryFirst(CarrierSql.STORED_ROW, listOf(id)) != null
            if (!stored) throw EntityNotFoundException("CARRIER", id)
        }
    }
}
