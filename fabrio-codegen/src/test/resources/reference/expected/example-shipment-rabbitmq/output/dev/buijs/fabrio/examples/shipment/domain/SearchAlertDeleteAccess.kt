            sql.batch(
                SearchAlertSql.DELETE,
                candidates.map { index ->
                    val item = items[index]
                    listOf(item.id, arrayOf(currentTenant.require(), actorScope.generate().toString()))
                },
            )
        val removed =
            candidates.filterIndexed { position, _ -> matched[position].isNotEmpty() }.toSet()
