            sql.batch(
                ShipmentSql.INSERT_PACKAGES_ON_UPDATE,
                elements.mapIndexed { index, (element, parentKey) ->
                    mapper.insertPackagesOnUpdate(element, parentKey, positions[index])
                },
            )
        return inserted.map { result ->
            sql.requireWritten(result, "SHIPMENT_PACKAGE", emptyList())
        }
    }

    /** Replaces every `packages` row of the parents with their command's elements. */
    private suspend fun replacePackages(
        sql: QueryExecutor,
        parents: List<Pair<Long, Collection<CreateShipmentPackageCommand>>>,
    ) {
        if (parents.isEmpty()) return
        removePackagesOf(sql, parents.map { it.first })
        val elements = parents.flatMap { (parentKey, elements) -> elements.map { it to parentKey } }
        insertPackagesOnUpdate(sql, elements, elements.indices.toList())
    }

    /**
     * Deletes every `packages` row of the parents: their nested rows first, their owned rows after.
     */
    private suspend fun removePackagesOf(
        sql: QueryExecutor,
        parentKeys: List<Long>,
    ) {
        if (parentKeys.isEmpty()) return
        sql.execute(ShipmentSql.DELETE_PACKAGES_OF, listOf(parentKeys.toTypedArray()))
    }

    /** Reads the written rows back through the read projection, in the order of [ids]. */
    private suspend fun readBack(
        sql: QueryExecutor,
        ids: List<UUID>,
    ): List<Versioned<Shipment>> =
        if (ids.isEmpty()) {
            emptyList()
        } else {
            sql
                .query(ShipmentSql.SELECT_BY_IDS, listOf(ids.toTypedArray(), currentTenant.require()))
                .inKeyOrder(ids, "id", "SHIPMENT")
                .map { Versioned(rowMapper.map(it), it.long("__version")) }
        }
}
