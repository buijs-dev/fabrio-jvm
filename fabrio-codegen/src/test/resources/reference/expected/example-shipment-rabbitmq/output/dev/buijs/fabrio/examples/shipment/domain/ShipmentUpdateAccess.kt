    private suspend fun insertPackagesOnUpdate(
        sql: QueryExecutor,
        elements: List<Pair<CreateShipmentPackageCommand, Long>>,
        positions: List<Int>,
    ): List<RowContext> {
        if (elements.isEmpty()) return emptyList()
