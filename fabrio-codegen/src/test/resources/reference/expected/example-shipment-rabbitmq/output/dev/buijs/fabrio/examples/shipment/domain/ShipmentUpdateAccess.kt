    private suspend fun update(
        sql: QueryExecutor,
        items: List<UpdateBatchItem<ShipmentId, UpdateShipment>>,
        transition: ShipmentTransition? = null,
    ): List<Result<Versioned<Shipment>>> {
        val rejected = rejected(items)
        val candidates = items.indices.filter { rejected[it] == null }
        val transitionActor = if (transition in setOf(ShipmentTransition.APPROVE)) actorScope.generate().toString() else null
        val updated =
            sql.batch(
                ShipmentSql.UPDATE,
                candidates.map { index ->
                    val item = items[index]
                    mapper.update(item.command, item.id, VERSION.valueOf(item.expectedVersion), currentTenant.require(), transition, transitionActor)
                },
            )

        // Missing references fail the whole batch.
        val rows = HashMap<Int, RowContext>()
        candidates.forEachIndexed { position, index ->
            val row = updated[position].singleOrNull()
            if (row == null) {
                sql.requireReferences(mapper.updateReferences(items[index].command))
            } else {
                rows[index] = row
            }
        }

        val matched = candidates.filter { it in rows }
        val tagsLinks =
            matched.mapNotNull { index ->
                val key = rows.getValue(index).long("storage_id")
                mapper.tags(items[index].command)?.let { key to it }
            }
        sql.requireAllReferenced(
            "TAG",
            "ID",
            ShipmentSql.EXISTING_TAGS,
            tagsLinks.flatMap { it.second }.distinct().toTypedArray(),
        )
        sql.batch(
            ShipmentSql.DELETE_TAGS_EXCEPT,
            tagsLinks.map { (key, ids) -> listOf(key, ids.toTypedArray()) },
        )
        sql.batch(
            ShipmentSql.INSERT_TAGS,
            tagsLinks
                .filter { it.second.isNotEmpty() }
                .map { (key, ids) -> listOf(key, ids.toTypedArray()) },
        )
        synchronizeLines(
            sql,
            matched.mapNotNull { index ->
                val key = rows.getValue(index).long("storage_id")
                mapper.lines(items[index].command)?.let { key to it }
            },
        )
        replacePackages(
            sql,
            matched.mapNotNull { index ->
                val key = rows.getValue(index).long("storage_id")
                mapper.packages(items[index].command)?.let { key to it }
            },
        )
        val entities = matched.zip(readBack(sql, matched.map { items[it].id.value })).toMap()
        return items.indices.map { index ->
            val item = items[index]
            rejected[index]?.let { Result.failure(it) }
                ?: entities[index]?.let { Result.success(it) }
                ?: Result.failure(
                    if (transition != null && sql.queryFirst(
                            ShipmentSql.CURRENT_ROW,
                            listOf(item.id.value, VERSION.valueOf(item.expectedVersion), currentTenant.require()),
                        ) != null
                    ) {
                        dev.buijs.fabrio.persistence.core.api.InvalidTransitionException("SHIPMENT", item.id.value, transition.rule)
                    } else {
                        if (true && sql.queryFirst(ShipmentSql.ACTIVE_ROW, listOf(item.id.value, currentTenant.require())) != null) {
                            dev.buijs.fabrio.persistence.core.api.OptimisticLockException("SHIPMENT", item.id.value, item.expectedVersion)
                        } else {
                            dev.buijs.fabrio.persistence.core.api.EntityNotFoundException("SHIPMENT", item.id.value)
                        }
                    },
                )
        }
    }

    /**
     * Inserts the `lines` elements of an update, each with its parent's key; returns their rows.
     */
    private suspend fun insertLinesOnUpdate(
        sql: QueryExecutor,
        elements: List<Pair<UpdateShipmentLine, Long>>,
        positions: List<Int>,
    ): List<RowContext> {
        if (elements.isEmpty()) return emptyList()
        val inserted =
            sql.batch(
                ShipmentSql.INSERT_LINES_ON_UPDATE,
                elements.mapIndexed { index, (element, parentKey) ->
                    mapper.insertLinesOnUpdate(element, parentKey, positions[index])
                },
            )
        return inserted.map { result -> sql.requireWritten(result, "SHIPMENT_LINE", emptyList()) }
    }

    /**
     * Synchronizes the `lines` rows of the parents with their command's elements by id: a
     * matching row is updated, a new element inserted, a row no element names any more removed. A
     * child is never moved to another parent, and an id may occur only once.
     */
    private suspend fun synchronizeLines(
        sql: QueryExecutor,
        parents: List<Pair<Long, Collection<UpdateShipmentLine>>>,
    ) {
        if (parents.isEmpty()) return
        val owners =
            sql
                .query(ShipmentSql.LINES_KEYS, listOf(parents.map { it.first }.toTypedArray()))
                .associate { it.uuid("public_id") to it.long("shipment_id") }
        val elements = parents.flatMap { (parentKey, elements) -> elements.map { it to parentKey } }
        val diff = ownedChildDiff("shipment_line", elements, { mapper.linesId(it) }, owners, owners.keys)
        // The index of each element in the submitted collection is its position.
        val positions = elements.indices.partition { mapper.linesId(elements[it].first) != null }
        val updates =
            sql.batch(
                ShipmentSql.UPDATE_LINES,
                diff.update.mapIndexed { index, (element, parentKey) ->
                    mapper.updateLines(element, parentKey, positions.first[index])
                },
            )
        updates.forEach { result -> sql.requireWritten(result, "SHIPMENT_LINE", emptyList()) }
        insertLinesOnUpdate(sql, diff.insert, positions.second)
        if (diff.remove.isNotEmpty()) removeLinesByIds(sql, diff.remove.toList())
    }

    /**
     * Deletes the `lines` rows no element names any more: their nested rows first, their owned rows
     * after.
     */
    private suspend fun removeLinesByIds(
        sql: QueryExecutor,
        ids: List<UUID>,
    ) {
        sql.execute(ShipmentSql.DELETE_LINES_BY_IDS, listOf(ids.toTypedArray()))
    }

    /**
