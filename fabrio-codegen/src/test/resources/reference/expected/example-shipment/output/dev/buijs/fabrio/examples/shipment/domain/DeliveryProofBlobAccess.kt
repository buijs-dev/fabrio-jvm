package dev.buijs.fabrio.examples.shipment.domain

import dev.buijs.fabrio.blob.BinaryContent
import dev.buijs.fabrio.blob.BlobKeys
import dev.buijs.fabrio.blob.BlobStore
import dev.buijs.fabrio.persistence.core.api.EntityNotFoundException
import dev.buijs.fabrio.persistence.reactive.spi.QueryExecutor
import dev.buijs.fabrio.persistence.reactive.spi.TransactionalExecutor
import dev.buijs.fabrio.security.quarkus.CurrentTenant
import jakarta.inject.Named
import jakarta.inject.Singleton

/**
 * Generated data access for `DeliveryProof` (persistence P7): `file` is kept in the
 * blob store `proofs`, the row of `delivery_proof` holds its key and metadata.
 * A write stores the content under a fresh key before the row commits; the content the
 * row referred to before is removed after the commit. Inside a caller's transaction it
 * stays behind, unreferenced and safe to remove later.
 *
 * Auto-generated by fabrio:codegen. Do not edit manually.
 */
@Singleton
internal class DeliveryProofBlobAccess(
    private val queryExecutor: QueryExecutor,
    private val transactionalExecutor: TransactionalExecutor,
    private val currentTenant: CurrentTenant,
    @param:Named("proofs") private val store: BlobStore,
    private val fileCheck: DeliveryProofFileCheck,
) {
    /** The DeliveryProof of [shipment] with its content opened, or `null`; read the content once. */
    suspend fun findById(shipment: ShipmentId): DeliveryProof? {
        val row = queryExecutor.queryFirst(FIND_BY_ID, listOf(shipment.value, currentTenant.require())) ?: return null
        val key = row.string("file_key")
        val input = store.open(key) ?: error("The content of DeliveryProof '$key' is missing from proofs")
        val file = BinaryContent.of(row.string("file_media_type"), row.long("file_size"), row.stringOrNull("file_sha256")?.trim()) { input }
        return DeliveryProof(shipment = shipment, file = file)
    }

    /** Stores [file] as the content of [shipment]: the check, the content, then the row (P7.2). The result has the stored metadata; read its content with findById. */
    suspend fun put(
        shipment: ShipmentId,
        file: BinaryContent,
    ): DeliveryProof {
        fileCheck.check(file)
        val tenant = currentTenant.require()
        val stored = store.put(BlobKeys.fresh("delivery_proof"), file)
        val joined = transactionalExecutor.isInTransaction()
        val replaced =
            try {
                transactionalExecutor.withTransaction { sql ->
                    val previous = sql.queryFirst(LOCK_BY_ID, listOf(shipment.value, tenant))?.string("file_key")
                    val written = sql.execute(UPSERT, listOf(shipment.value, stored.key, file.mediaType, stored.size, stored.sha256, tenant))
                    if (written != 1) throw EntityNotFoundException("delivery_proof", shipment.value)
                    previous
                }
            } catch (e: Throwable) {
                runCatching { store.delete(stored.key) }
                throw e
            }

        if (replaced != null && !joined) runCatching { store.delete(replaced) }
        return DeliveryProof(shipment = shipment, file = BinaryContent.of(file.mediaType, stored.size, stored.sha256) { error("Read the stored content of shipment with findById") })
    }

    /** Deletes the row of [shipment], then its content; `false` when there was none. */
    suspend fun delete(shipment: ShipmentId): Boolean {
        val joined = transactionalExecutor.isInTransaction()
        val key =
            transactionalExecutor.withTransaction { sql ->
                sql.queryFirst(DELETE_BY_ID, listOf(shipment.value, currentTenant.require()))?.string("file_key")
            } ?: return false

        if (!joined) runCatching { store.delete(key) }
        return true
    }

    private companion object {
        const val FIND_BY_ID = "SELECT file_key, file_media_type, file_size, file_sha256 FROM delivery_proof WHERE shipment_id = $1 AND tenant_id = $2"
        const val LOCK_BY_ID = "SELECT file_key FROM delivery_proof WHERE shipment_id = $1 AND tenant_id = $2 FOR UPDATE"
        const val UPSERT = "INSERT INTO delivery_proof (shipment_id, file_key, file_media_type, file_size, file_sha256, tenant_id) VALUES ($1, $2, $3, $4, $5, $6) ON CONFLICT (shipment_id) DO UPDATE SET file_key = EXCLUDED.file_key, file_media_type = EXCLUDED.file_media_type, file_size = EXCLUDED.file_size, file_sha256 = EXCLUDED.file_sha256 WHERE delivery_proof.tenant_id = EXCLUDED.tenant_id"
        const val DELETE_BY_ID = "DELETE FROM delivery_proof WHERE shipment_id = $1 AND tenant_id = $2 RETURNING file_key"
    }
}
