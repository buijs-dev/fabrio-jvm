package dev.buijs.fabrio.examples.shipment.domain

import dev.buijs.fabrio.entity.core.api.PatchField
import dev.buijs.fabrio.http.wire.Presence

/**
 * Converts a `Presence<T>`-wrapped update-request property into a
 * `PatchField<R>` - absent ([Presence.isPresent] `false`) becomes
 * [PatchField.Unset]; present (possibly itself `null`) becomes
 * `PatchField.Value([mapper] applied to the unwrapped value)`. [mapper] may
 * return `null`, such as a `TypeConverter` does, since a value may be `null`.
 *
 * Auto-generated by fabrio:codegen. Do not edit manually.
 */
internal fun <T, R> Presence<T>.toPatchField(mapper: (T) -> R?): PatchField<R> =
    when {
        !isPresent -> PatchField.Unset
        else -> PatchField.Value(mapper(get()))
    }

/** Unwraps a replace property; absent and explicit null both become null. */
internal fun <T> Presence<T?>?.replaceValue(): T? = this?.orElse(null)

/** Plain request models use the same replace semantics. */
internal fun <T> T?.replaceValue(): T? = this
