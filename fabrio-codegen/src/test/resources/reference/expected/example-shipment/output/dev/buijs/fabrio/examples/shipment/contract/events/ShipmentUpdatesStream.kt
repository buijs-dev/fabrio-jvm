            .open(SPEC, lastEventId, subscriberTenant) { access.canRead(principal, it) }
            .map { sse.newEventBuilder().id(it.id).name(it.type).data(CloudEventJson.encode(it)).build() }
    }

    private companion object {
        val SPEC =
            StreamSpec(
                name = "shipmentUpdates",
                types = setOf("com.example.shipment.approved.v1"),
                replay = Duration.parse("PT1H"),
            )
    }
}
