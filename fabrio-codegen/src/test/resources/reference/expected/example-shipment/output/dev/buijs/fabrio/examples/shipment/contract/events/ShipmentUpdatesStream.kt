@Path("/streams/shipments")
@ApplicationScoped
internal class ShipmentUpdatesStream(
    private val hub: StreamHub,
    private val access: ShipmentUpdatesAccess,
    private val identity: SecurityIdentity,
) {
    @GET
    @Produces(MediaType.SERVER_SENT_EVENTS)
    @RolesAllowed("shipments:read")
    fun stream(
        @HeaderParam("Last-Event-ID") lastEventId: String?,
        @Context sse: Sse,
    ): Multi<OutboundSseEvent> {
        val principal = identity.principal
        val subscriberTenant = identity.getAttribute<Any?>(TENANT_ATTRIBUTE)?.toString()
