    /**
     * Updates [items] at once, with a result for each item.
     * When the batch fails, every item is updated on its own instead.
     */
    override suspend fun updateAll(
        items: List<UpdateBatchItem<UUID, UpdateCarrier>>,
    ): BatchResult<Carrier> =
        batchOrEach(
            items,
            all = { all ->
                transactionalExecutor.withTransaction { sql -> update(sql, all) }
