            val item = items[index]
            rejected[index]?.let { Result.failure(it) }
                ?: entities[index]?.let { Result.success(it) }
                ?: Result.failure(
                    sql.diagnoseMiss(
                        "CARRIER",
                        CarrierSql.ACTIVE_ROW,
                        item.id,
                        item.expectedVersion,
                        versioned = false,
                    ),
                )
        }
    }

    /** Reads the written rows back through the read projection, in the order of [ids]. */
