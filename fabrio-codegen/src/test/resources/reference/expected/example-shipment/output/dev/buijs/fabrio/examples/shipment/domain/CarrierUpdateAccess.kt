            each = { update(it.id, it.command, it.expectedVersion) },
            rejected = rejected(items),
        )

    private fun rejected(items: List<UpdateBatchItem<UUID, UpdateCarrier>>): List<Throwable?> =
        rejectedInputs(
            "CARRIER",
            items.map { it.id },
            items.map { it.expectedVersion },
            null,
        )

    private suspend fun update(
        sql: QueryExecutor,
        items: List<UpdateBatchItem<UUID, UpdateCarrier>>,
    ): List<Result<Carrier>> {
        val rejected = rejected(items)
        val candidates = items.indices.filter { rejected[it] == null }
        val updated =
            sql.batch(
                CarrierSql.UPDATE,
                candidates.map { index ->
                    val item = items[index]
                    mapper.update(item.command, item.id)
                },
            )

        // Missing references fail the whole batch.
        val rows = HashMap<Int, RowContext>()
        candidates.forEachIndexed { position, index ->
            val row = updated[position].singleOrNull()
            if (row == null) {
                sql.requireReferences(emptyList())
            } else {
                rows[index] = row
            }
        }

        val matched = candidates.filter { it in rows }
        val entities = matched.zip(readBack(sql, matched.map { items[it].id })).toMap()
