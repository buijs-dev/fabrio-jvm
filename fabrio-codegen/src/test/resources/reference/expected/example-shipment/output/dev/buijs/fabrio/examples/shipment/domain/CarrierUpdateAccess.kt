        sql: QueryExecutor,
        ids: List<UUID>,
    ): List<Carrier> =
        if (ids.isEmpty()) {
            emptyList()
        } else {
            sql
                .query(CarrierSql.SELECT_BY_IDS, listOf(ids.toTypedArray()))
                .inKeyOrder(ids, "id", "CARRIER")
                .map(rowMapper::map)
        }
}
